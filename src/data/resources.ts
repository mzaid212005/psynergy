// Get resources by category
export function getResourcesByCategory(categoryId: string): Resource[] {
  return resources.filter(resource => 
    resource.category.toLowerCase().replace(' ', '_') === categoryId
  )
}

// Get resources by tag
export function getResourcesByTag(tag: string): Resource[] {
  return resources.filter(resource =>
    resource.tags.some(resourceTag => 
      resourceTag.toLowerCase().includes(tag.toLowerCase())
    )
  )
}

// Get resources by difficulty
export function getResourcesByDifficulty(difficulty: string): Resource[] {
  return resources.filter(resource => resource.difficulty === difficulty)
}

// Get resources by type
export function getResourcesByType(type: string): Resource[] {
  return resources.filter(resource => resource.type === type)
}

// Search resources
export function searchResources(query: string): Resource[] {
  const searchTerm = query.toLowerCase()
  return resources.filter(resource =>
    resource.title.toLowerCase().includes(searchTerm) ||
    resource.description.toLowerCase().includes(searchTerm) ||
    resource.tags.some(tag => tag.toLowerCase().includes(searchTerm)) ||
    resource.content.toLowerCase().includes(searchTerm)
  )
}

// Get recommended resources based on user profile
export function getRecommendedResources(userInterests: string[], userLevel: string = 'beginner'): Resource[] {
  return resources
    .filter(resource => 
      resource.difficulty === userLevel ||
      resource.tags.some(tag => userInterests.includes(tag))
    )
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
    .slice(0, 6)
}
